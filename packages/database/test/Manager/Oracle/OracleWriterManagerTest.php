<?php

declare(strict_types=1);

namespace Windwalker\Database\Test\Manager\Oracle;

use Windwalker\Database\Platform\DbPlatform;
use Windwalker\Database\Test\Manager\AbstractUpsertTestCase;

class OracleWriterManagerTest extends AbstractUpsertTestCase
{
    protected static DbPlatform $platform = DbPlatform::Oracle;

    protected static string $driver = 'pdo_oci';

    protected static function createUpsertTable(): void
    {
        self::$baseConn->exec(
            "BEGIN EXECUTE IMMEDIATE 'DROP TABLE ww_upsert_items CASCADE CONSTRAINTS PURGE'; "
            . 'EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;'
        );
        self::$baseConn->exec(
            'CREATE TABLE ww_upsert_items '
            . '(id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR2(100) NOT NULL UNIQUE, '
            . 'state NUMBER(10) NULL)'
        );
    }
}
