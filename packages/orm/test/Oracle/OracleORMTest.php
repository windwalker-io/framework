<?php

declare(strict_types=1);

namespace Windwalker\ORM\Test\Oracle;

use PHPUnit\Framework\Attributes\Test;
use Windwalker\Database\Platform\DbPlatform;
use Windwalker\ORM\Test\AbstractORMTestCase;
use Windwalker\ORM\Test\Entity\StubOracleFlower;

class OracleORMTest extends AbstractORMTestCase
{
    protected static DbPlatform $platform = DbPlatform::Oracle;

    protected static string $driver = 'pdo_oci';

    #[Test]
    public function createFillsAutoIncrementId(): void
    {
        $mapper = self::$orm->mapper(StubOracleFlower::class);

        $item = new StubOracleFlower();
        $item->title = 'Rose';
        $item->params = ['a' => 1];

        $item = $mapper->createOne($item);

        self::assertGreaterThan(0, $item->id);

        $found = $mapper->findOne($item->id);

        self::assertEquals('Rose', $found->title);
        self::assertEquals(['a' => 1], $found->params);
    }

    #[Test]
    public function updateAndDeleteWork(): void
    {
        $mapper = self::$orm->mapper(StubOracleFlower::class);

        $item = new StubOracleFlower();
        $item->title = 'Tulip';
        $item = $mapper->createOne($item);

        $item->title = 'Lily';
        $mapper->updateOne($item);

        self::assertEquals('Lily', $mapper->findOne($item->id)->title);

        $mapper->deleteWhere(['id' => $item->id]);

        self::assertNull($mapper->findOne($item->id));
    }

    #[Test]
    public function saveManyAndSelectWithLimit(): void
    {
        $mapper = self::$orm->mapper(StubOracleFlower::class);

        $items = [];

        foreach (['X1', 'X2', 'X3'] as $title) {
            $item = new StubOracleFlower();
            $item->title = $title;
            $items[] = $item;
        }

        $mapper->createMultiple($items);

        $rows = $mapper->select()
            ->where('title', 'like', 'X%')
            ->order('title', 'DESC')
            ->limit(2)
            ->offset(1)
            ->all();

        self::assertEquals(['X2', 'X1'], $rows->column('title')->dump());
    }

    #[Test]
    public function saveUpsertsByKey(): void
    {
        $mapper = self::$orm->mapper(StubOracleFlower::class);

        $item = new StubOracleFlower();
        $item->title = 'Orchid';
        $item = $mapper->saveOne($item);

        $id = $item->id;
        $item->state = 1;
        $mapper->saveOne($item);

        self::assertSame($id, $item->id);
        self::assertEquals(1, $mapper->findOne($id)->state);
    }

    protected static function setupDatabase(): void
    {
        self::$baseConn->exec(
            'CREATE TABLE ww_oracle_flower ('
            . 'id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            . 'title VARCHAR2(255) NULL, state NUMBER(3) DEFAULT 0 NOT NULL, params CLOB NULL)'
        );
    }
}
